def add_textbox(slide, left, top, width, height, text,
                font_name=KOR, font_size=14, bold=False,
                color=NAVY, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP):
    tb = slide.shapes.add_textbox(Inches(left), Inches(top),
                                  Inches(width), Inches(height))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = Inches(0.05)
    tf.margin_right = Inches(0.05)
    tf.margin_top = Inches(0.02)
    tf.margin_bottom = Inches(0.02)
    tf.vertical_anchor = anchor
    lines = text.split('\n')
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        run = p.add_run()
        run.text = line
        run.font.name = font_name
        run.font.size = Pt(font_size)
        run.font.bold = bold
        run.font.color.rgb = color
    return tb


def add_rect(slide, left, top, width, height, fill_color=None, line_color=None):
    rect = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE,
                                  Inches(left), Inches(top),
                                  Inches(width), Inches(height))
    rect.shadow.inherit = False
    if fill_color is not None:
        rect.fill.solid()
        rect.fill.fore_color.rgb = fill_color
    else:
        rect.fill.background()
    if line_color is None:
        rect.line.fill.background()
    else:
        rect.line.color.rgb = line_color
    rect.text_frame.text = ''
    return rect


def add_top_band(slide):
    add_rect(slide, 0.0, 0.0, 13.33, 0.40, fill_color=NAVY)


def add_bottom_band(slide):
    add_rect(slide, 0.0, 7.10, 13.33, 0.40, fill_color=DARKRED)


def add_header(slide, section_text, page_num, total):
    add_textbox(slide, 0.50, 0.30, 10.00, 0.30,
                section_text, font_size=11, bold=True, color=SLATE)
    add_textbox(slide, 12.00, 0.30, 1.30, 0.30,
                f"{page_num} / {total}", font_size=10, color=SLATE,
                align=PP_ALIGN.RIGHT)


def add_title(slide, title, subtitle=None):
    add_textbox(slide, 0.50, 0.85, 12.80, 0.70,
                title, font_size=28, bold=True, color=NAVY)
    if subtitle:
        add_textbox(slide, 0.50, 1.55, 12.80, 0.40,
                    subtitle, font_size=14, color=SLATE)


def add_section_panel(slide, top, height, title, body_lines,
                      bg=LBLUE, title_color=DARKRED, body_color=NAVY,
                      title_size=15, body_size=13, left=0.50, width=12.30):
    add_rect(slide, left, top, width, height, fill_color=bg)
    add_textbox(slide, left + 0.20, top + 0.08, width - 0.40, 0.42,
                title, font_size=title_size, bold=True, color=title_color)
    add_textbox(slide, left + 0.20, top + 0.52, width - 0.40, height - 0.58,
                '\n'.join(body_lines), font_size=body_size, color=body_color)


def build_content_slide(prs, page, section, title, subtitle, blocks):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    add_header(slide, section, page, TOTAL)
    add_title(slide, title, subtitle)
    n = len(blocks)
    avail_top = 2.10
    avail_h = 5.00
    gap = 0.14
    if n == 0:
        return
    bh = (avail_h - gap * (n - 1)) / n
    for idx, (ptitle, plines) in enumerate(blocks):
        top = avail_top + idx * (bh + gap)
        add_section_panel(slide, top, bh, ptitle, plines)


def build_kv_slide(prs, page, section, title, subtitle, rows,
                   label_w=2.0, row_h=None, top_start=2.10):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    add_header(slide, section, page, TOTAL)
    add_title(slide, title, subtitle)
    n = len(rows)
    if row_h is None:
        avail = 7.10 - top_start
        row_h = min(0.62, avail / n)
    for i, (lbl, val) in enumerate(rows):
        top = top_start + i * row_h
        add_rect(slide, 0.50, top, label_w + 0.10, row_h - 0.05,
                 fill_color=LBLUE)
        f_sz = 13 if row_h >= 0.55 else 12
        add_textbox(slide, 0.60, top + 0.05, label_w, row_h - 0.10,
                    lbl, font_size=f_sz, bold=True, color=DARKRED,
                    anchor=MSO_ANCHOR.MIDDLE)
        add_textbox(slide, 0.50 + label_w + 0.25, top + 0.05,
                    12.80 - label_w - 0.30, row_h - 0.10,
                    val, font_size=f_sz, color=NAVY, anchor=MSO_ANCHOR.MIDDLE)


