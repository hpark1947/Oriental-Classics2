        ('Ⅱ.', '시대 배경 — 약육강식의 200년'),
        ('Ⅲ.', '책의 정체 — 유향의 편집'),
        ('Ⅳ.', '12국 33편의 구성'),
        ('Ⅴ.', '11국 깊이 읽기'),
        ('Ⅵ.', '두 주인공 — 소진·장의'),
        ('Ⅶ.', '전국 사군자'),
        ('Ⅷ.', '의인·자객 — 인상여·형가'),
        ('Ⅸ.', '책사·명장 — 진을 만든 자들'),
        ('Ⅹ.', '종횡가의 사상'),
        ('Ⅺ.', '명구·고사성어 22선'),
        ('Ⅻ.', '진의 통일과 15년 멸망'),
